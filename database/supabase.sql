-- Run using npm run db:setup, or paste into your Supabase SQL editor.
-- Application-only schema; deliberately separate from public and auth.users.
-- No existing databases/tables are dropped and no application records are replaced.
CREATE SCHEMA IF NOT EXISTS zendx;
REVOKE ALL ON SCHEMA zendx FROM PUBLIC;

CREATE TABLE IF NOT EXISTS zendx.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'editor',
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.social_accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES zendx.users(id) ON DELETE CASCADE,
  provider VARCHAR(80) NOT NULL,
  remote_account_id VARCHAR(255),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  account_name VARCHAR(150),
  access_token TEXT,
  refresh_token TEXT,
  expires_at TIMESTAMP,
  config TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
-- Upgrade earlier shared-account installations without guessing ownership.
-- Legacy rows remain unassigned/invisible until their owner reconnects.
ALTER TABLE zendx.social_accounts ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES zendx.users(id) ON DELETE CASCADE;
ALTER TABLE zendx.social_accounts ADD COLUMN IF NOT EXISTS remote_account_id VARCHAR(255);
ALTER TABLE zendx.social_accounts ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;
CREATE UNIQUE INDEX IF NOT EXISTS social_accounts_identity_idx ON zendx.social_accounts(user_id,provider,remote_account_id);
CREATE INDEX IF NOT EXISTS social_accounts_owner_idx ON zendx.social_accounts(user_id);
CREATE TABLE IF NOT EXISTS zendx.posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id INTEGER REFERENCES zendx.users(id) ON DELETE SET NULL,
  title VARCHAR(255),
  body TEXT,
  media_url VARCHAR(255),
  scheduled_at TIMESTAMP,
  status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','published','failed')),
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.post_targets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES zendx.posts(id) ON DELETE CASCADE,
  social_account_id INTEGER NOT NULL REFERENCES zendx.social_accounts(id) ON DELETE CASCADE,
  provider_post_id VARCHAR(255),
  status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','failed')),
  error_message TEXT,
  published_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.post_comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_target_id INTEGER NOT NULL REFERENCES zendx.post_targets(id) ON DELETE CASCADE,
  commenter_name VARCHAR(255),
  comment TEXT NOT NULL,
  external_id VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS comments_external_idx ON zendx.post_comments(post_target_id,external_id) WHERE external_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS zendx.analytics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES zendx.posts(id) ON DELETE CASCADE,
  impressions INTEGER NOT NULL DEFAULT 0,
  clicks INTEGER NOT NULL DEFAULT 0,
  engagements INTEGER NOT NULL DEFAULT 0,
  metric_date DATE,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES zendx.users(id) ON DELETE CASCADE,
  token VARCHAR(255) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.customer_chats (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_email VARCHAR(150) NOT NULL,
  customer_name VARCHAR(100),
  message TEXT NOT NULL,
  is_admin_reply BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.calendar_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES zendx.posts(id) ON DELETE CASCADE,
  "start" TIMESTAMP NOT NULL,
  "end" TIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  description TEXT,
  created_by INTEGER REFERENCES zendx.users(id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE TABLE IF NOT EXISTS zendx.campaign_posts (
  campaign_id INTEGER NOT NULL REFERENCES zendx.campaigns(id) ON DELETE CASCADE,
  post_id INTEGER NOT NULL REFERENCES zendx.posts(id) ON DELETE CASCADE,
  PRIMARY KEY (campaign_id,post_id)
);
CREATE TABLE IF NOT EXISTS zendx.delivery_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id INTEGER NOT NULL REFERENCES zendx.post_targets(id) ON DELETE CASCADE,
  attempted_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  success BOOLEAN NOT NULL,
  error_message TEXT
);
CREATE TABLE IF NOT EXISTS zendx.app_sessions (
  sid VARCHAR(128) PRIMARY KEY,
  expires BIGINT NOT NULL,
  data TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS app_sessions_expires_idx ON zendx.app_sessions(expires);
CREATE INDEX IF NOT EXISTS posts_schedule_idx ON zendx.posts(scheduled_at) WHERE status='scheduled';
CREATE INDEX IF NOT EXISTS posts_author_idx ON zendx.posts(author_id);
CREATE INDEX IF NOT EXISTS post_targets_post_idx ON zendx.post_targets(post_id);
CREATE INDEX IF NOT EXISTS post_targets_account_idx ON zendx.post_targets(social_account_id);
CREATE INDEX IF NOT EXISTS comments_target_idx ON zendx.post_comments(post_target_id);
CREATE INDEX IF NOT EXISTS analytics_post_idx ON zendx.analytics(post_id);
CREATE INDEX IF NOT EXISTS reset_user_idx ON zendx.password_resets(user_id);
CREATE INDEX IF NOT EXISTS attempts_target_idx ON zendx.delivery_attempts(target_id);

CREATE OR REPLACE FUNCTION zendx.set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  NEW.updated_at = LOCALTIMESTAMP;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS posts_updated_at ON zendx.posts;
CREATE TRIGGER posts_updated_at BEFORE UPDATE ON zendx.posts
FOR EACH ROW EXECUTE FUNCTION zendx.set_updated_at();

-- This backend owns authentication. Anonymous/browser Supabase API keys must
-- never read session data, password hashes or social-provider tokens.
-- RLS with no browser policies denies access; Node connects as the schema owner.
DO $$
DECLARE tab RECORD; api_role TEXT;
BEGIN
  FOR tab IN SELECT tablename FROM pg_tables WHERE schemaname='zendx' LOOP
    EXECUTE format('ALTER TABLE zendx.%I ENABLE ROW LEVEL SECURITY', tab.tablename);
  END LOOP;
  REVOKE ALL ON ALL TABLES IN SCHEMA zendx FROM PUBLIC;
  REVOKE ALL ON ALL SEQUENCES IN SCHEMA zendx FROM PUBLIC;
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA zendx FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA zendx FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA zendx FROM %I',api_role);
    END IF;
  END LOOP;
END;
$$;
ALTER DEFAULT PRIVILEGES IN SCHEMA zendx REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA zendx REVOKE ALL ON SEQUENCES FROM PUBLIC;
