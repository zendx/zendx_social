// A destructive cleanup is allowed ONLY for the new, prefixed database this script creates.
import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import mysql from 'mysql2/promise';
import bcrypt from 'bcryptjs';
import request from 'supertest';
import { database } from '../server/config.js';
import { createApp } from '../server/app.js';
import { SQLSessionStore } from '../server/session-store.js';
import { processQueue } from '../server/worker.js';

const name = process.env.TEST_DB_NAME;
if (!name || !/^zendx_test_[a-z0-9_]+$/.test(name) || name === database.database) throw new Error('Set TEST_DB_NAME to a NEW empty database name beginning zendx_test_. The application database is forbidden.');
const settings = { ...database, port: Number(process.env.TEST_DB_PORT || database.port), database: undefined };
const admin = await mysql.createConnection(settings);
let created = false;
let testPool;
try {
  const [existing] = await admin.execute('SELECT SCHEMA_NAME FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=?', [name]);
  assert.equal(existing.length, 0, 'Test database already exists; refusing to modify it.');
  await admin.query('CREATE DATABASE ??', [name]);
  created = true;
  const setup = spawnSync(process.execPath, ['server/setup.js'], { env: { ...process.env, DB_NAME: name, DB_PORT: String(settings.port), ADMIN_EMAIL: '', ADMIN_PASSWORD: '' }, encoding: 'utf8', timeout: 30000 });
  assert.equal(setup.status, 0, setup.stderr || setup.error?.message);
  // Setup must be safe to run repeatedly with existing data.
  testPool = mysql.createPool({ ...settings, database: name });
  testPool.on('connection', conn => conn.query('SET time_zone = ?', [database.timezone]));
  const db = async (sql, values = []) => (await testPool.execute(sql, values))[0];
  const store = new SQLSessionStore(testPool);
  await store.initialize();
  const legacyHash = (await bcrypt.hash('legacy-password', 4)).replace('$2b$', '$2y$');
  await db('INSERT INTO users (name,email,password_hash,role) VALUES (?,?,?,?)', ['Legacy Admin', 'legacy@example.com', legacyHash, 'admin']);
  const rerun = spawnSync(process.execPath, ['server/setup.js'], { env: { ...process.env, DB_NAME: name, DB_PORT: String(settings.port), ADMIN_EMAIL: '', ADMIN_PASSWORD: '' }, encoding: 'utf8', timeout: 30000 });
  assert.equal(rerun.status, 0, rerun.stderr);
  assert.equal((await db('SELECT COUNT(*) AS n FROM users'))[0].n, 1);
  let resetUrl;
  const app = createApp({ db, pool: testPool, sessionStore: store, sessionSecret: randomBytes(32).toString('hex'), sendMail: async (email, url) => { resetUrl = url; } });
  const agent = request.agent(app);
  let csrf = (await agent.get('/api/session')).body.csrf;
  let response = await agent.post('/api/auth/login').set('X-CSRF-Token', csrf).send({ email: 'legacy@example.com', password: 'legacy-password' });
  assert.equal(response.status, 200, JSON.stringify(response.body));
  csrf = response.body.csrf;
  const account = await db('INSERT INTO social_accounts (provider,account_name,config) VALUES (?,?,?)', ['facebook', 'Isolated test page', '{}']);
  const account2 = await db('INSERT INTO social_accounts (provider,account_name,config) VALUES (?,?,?)', ['twitter', 'Isolated test X', '{}']);
  const send = (route, body, method = 'post') => agent[method](route).set('X-CSRF-Token', csrf).send(body);
  response = await send('/api/posts', { title: 'Never publish this draft', body: 'Draft', account_ids: [account.insertId] });
  assert.equal(response.status, 201, JSON.stringify(response.body));
  const draftId = response.body.id;
  response = await send('/api/posts', { title: 'Future', body: 'Later', scheduled_at: '2099-01-01T09:00', account_ids: [account.insertId] });
  assert.equal(response.status, 201, JSON.stringify(response.body));
  response = await send('/api/posts', { title: 'Ready', body: 'Now', publish_now: true, account_ids: [account.insertId, account2.insertId] });
  assert.equal(response.status, 201, JSON.stringify(response.body));
  const scheduledId = response.body.id;
  const sent = [];
  const fakePublish = async (provider, config, post) => { sent.push(post.id); if (provider === 'twitter') throw new Error('Test provider failure'); return 'test-external-id'; };
  const results = await processQueue(testPool, fakePublish);
  assert.deepEqual(results, { published: 1, failed: 1 });
  assert.deepEqual(sent, [scheduledId, scheduledId]);
  assert.equal((await db('SELECT status FROM posts WHERE id=?', [draftId]))[0].status, 'draft');
  assert.equal((await db('SELECT status FROM posts WHERE id=?', [scheduledId]))[0].status, 'failed');
  const targets = await db('SELECT * FROM post_targets WHERE post_id=?', [scheduledId]);
  const failed = targets.find(t => t.status === 'failed');
  response = await send(`/posts/${scheduledId}`, { body: 'Changed', account_ids: [] }, 'put');
  // Correct API route below: an unknown route must not fall through to the SPA.
  assert.equal(response.status, 404);
  response = await send(`/api/posts/${scheduledId}`, { body: 'Changed', account_ids: [] }, 'put');
  assert.equal(response.status, 409);
  response = await send(`/api/targets/${failed.id}/retry`, {});
  assert.equal(response.status, 200, JSON.stringify(response.body));
  assert.deepEqual(await processQueue(testPool, async () => 'retry-id'), { published: 1, failed: 0 });
  assert.equal((await db('SELECT status FROM posts WHERE id=?', [scheduledId]))[0].status, 'published');
  response = await send('/api/comments', { target_id: targets[0].id, comment: 'Internal note only' });
  assert.equal(response.status, 201);
  response = await agent.get('/api/workspace');
  assert.equal(response.status, 200, JSON.stringify(response.body));
  assert.equal(response.body.comments.length, 1);
  assert.equal(response.body.accounts.some(a => 'config' in a || 'access_token' in a), false);
  response = await agent.post('/api/uploads').set('X-CSRF-Token', csrf).attach('media', Buffer.from('not-an-image'), { filename: 'fake.png', contentType: 'image/png' });
  assert.equal(response.status, 400);
  response = await send('/api/auth/forgot-password', { email: 'legacy@example.com' });
  assert.equal(response.status, 200, JSON.stringify(response.body));
  const token = new URL(resetUrl).searchParams.get('reset');
  assert.ok(token);
  assert.notEqual((await db('SELECT token FROM password_resets'))[0].token, token);
  response = await send('/api/auth/reset-password', { token, password: 'a-new-long-password' });
  assert.equal(response.status, 200);
  assert.equal((await send('/api/auth/reset-password', { token, password: 'another-password' })).status, 400);
  await send('/api/auth/logout', {});
  csrf = (await agent.get('/api/session')).body.csrf;
  response = await send('/api/auth/login', { email: 'legacy@example.com', password: 'a-new-long-password' });
  assert.equal(response.status, 200);
  console.log('Real MySQL integration passed: additive setup, PHP password compatibility, sessions, draft/future exclusion, mixed delivery results, retry, notes, upload validation, and single-use hashed password resets.');
} finally {
  if (testPool) await testPool.end();
  if (created && /^zendx_test_[a-z0-9_]+$/.test(name) && name !== database.database) await admin.query('DROP DATABASE ??', [name]);
  await admin.end();
}
